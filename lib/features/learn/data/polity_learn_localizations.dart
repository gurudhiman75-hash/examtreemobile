LearnSubject polityLearnSubjectFor(QuestionLanguage language) {
  if (language == QuestionLanguage.english) return polityLearnSubject;

  final localized = switch (language) {
    QuestionLanguage.hindi => _hindiLessons,
    QuestionLanguage.punjabi => _punjabiLessons,
    QuestionLanguage.english => const <String, LearnLesson>{},
  };

  final title = language == QuestionLanguage.hindi
      ? 'भारतीय राजव्यवस्था'
      : 'ਭਾਰਤੀ ਰਾਜ-ਵਿਵਸਥਾ';
  final subtitle = language == QuestionLanguage.hindi
      ? 'संविधान, अधिकारों, संस्थाओं और शासन को प्रतियोगी परीक्षाओं के लिए सरल तरीके से पढ़ें।'
      : 'ਸੰਵਿਧਾਨ, ਅਧਿਕਾਰਾਂ, ਸੰਸਥਾਵਾਂ ਅਤੇ ਸ਼ਾਸਨ ਨੂੰ ਮੁਕਾਬਲੇ ਦੀਆਂ ਪ੍ਰੀਖਿਆਵਾਂ ਲਈ ਸੌਖੇ ਢੰਗ ਨਾਲ ਪੜ੍ਹੋ।';

  return LearnSubject(
    code: polityLearnSubject.code,
    title: title,
    subtitle: subtitle,
    iconName: polityLearnSubject.iconName,
    lessons: polityLearnSubject.lessons
        .map((lesson) => localized[lesson.id] ?? lesson)
        .toList(growable: false),
  );
}

